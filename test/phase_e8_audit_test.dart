import 'dart:convert';
import 'dart:io';
import 'package:decidix_app/api/models/decisions.dart';
import 'package:decidix_app/core/auth/auth_controller.dart';
import 'package:decidix_app/core/config/app_config.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:shared_preferences/shared_preferences.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  setUp(() {
    SharedPreferences.setMockInitialValues({});
  });

  group('Phase E8 Audit Tests — Authentication & Data Provenance', () {
    // 1. Missing Google Server Client ID
    test('1. Missing Google Server Client ID raises diagnostic StateError', () {
      final container = ProviderContainer();
      addTearDown(container.dispose);

      final notifier = container.read(authNotifierProvider.notifier);

      expect(
        () => notifier.validateGoogleConfiguration(candidateServerClientId: ''),
        throwsA(
          isA<StateError>().having(
            (e) => e.message,
            'message',
            contains('serverClientId must be provided on Android'),
          ),
        ),
      );

      expect(
        () => notifier.validateGoogleConfiguration(candidateServerClientId: '   '),
        throwsA(
          isA<StateError>().having(
            (e) => e.message,
            'message',
            contains('serverClientId must be provided on Android'),
          ),
        ),
      );
    });

    // 2. Correct Google Server Client ID propagation
    test('2. Correct Google Server Client ID propagation across build configs', () {
      expect(AppConfig.defaultGoogleServerClientId, isNotEmpty);
      expect(
        AppConfig.defaultGoogleServerClientId,
        '50086376748-676lft8efht29skofqs9ouk3ic8nldue.apps.googleusercontent.com',
      );
      expect(AppConfig.googleServerClientId, isNotEmpty);
      expect(AppConfig.googleServerClientId, AppConfig.defaultGoogleServerClientId);
      expect(AppConfig.googleServerClientId, contains('apps.googleusercontent.com'));

      final container = ProviderContainer();
      addTearDown(container.dispose);
      final notifier = container.read(authNotifierProvider.notifier);

      // Validation passes cleanly with the default configured ID
      expect(() => notifier.validateGoogleConfiguration(), returnsNormally);
    });

    // 3. API failure without fake data appearing
    test('3. API failure produces explicit error state without fabricating data', () {
      // Simulate an error state in AuthState / API
      const failedAuthState = AuthState(
        errorMessage: 'Backend token verification failed: 500 Internal Server Error',
        isLoading: false,
      );

      expect(failedAuthState.isAuthenticated, isFalse);
      expect(failedAuthState.user, isNull);
      expect(failedAuthState.accessToken, isNull);
      expect(failedAuthState.errorMessage, contains('500 Internal Server Error'));
    });

    // 4. Explicit simulated-data labeling & lineage check
    test('4. Datasets lineage explicitly records generation script (SIMULATED)', () {
      final catalogFile = File('datasets/metadata/dataset_catalog.json');
      expect(catalogFile.existsSync(), isTrue, reason: 'dataset_catalog.json must exist');

      final content = catalogFile.readAsStringSync();
      final Map<String, dynamic> json = jsonDecode(content) as Map<String, dynamic>;
      final datasets = json['datasets'] as List<dynamic>;

      expect(datasets, isNotEmpty);
      for (final dataset in datasets) {
        final lineage = dataset['lineage'] as Map<String, dynamic>?;
        expect(lineage, isNotNull);
        expect(
          lineage!['transformation_script'],
          'scripts/pipeline_ingest.py',
          reason: 'Lineage confirms data is generated by pipeline_ingest.py',
        );
      }
    });

    // 5. Dataset provenance metadata classifications
    test('5. Regions and dataset metadata reflect synthetic simulation models', () {
      final catalogFile = File('datasets/metadata/dataset_catalog.json');
      final content = catalogFile.readAsStringSync();
      final Map<String, dynamic> json = jsonDecode(content) as Map<String, dynamic>;
      final datasets = json['datasets'] as List<dynamic>;

      final datasetIds = datasets.map((d) => d['id']).toList();
      expect(datasetIds, contains('decidix_health_indicators_v1'));
      expect(datasetIds, contains('decidix_education_indicators_v1'));
      expect(datasetIds, contains('decidix_economy_employment_v1'));
      expect(datasetIds, contains('decidix_infrastructure_cadastre_v1'));

      // Verify that geographic coverage uses synthetic simulation region slugs
      final healthDataset = datasets.firstWhere(
        (d) => d['id'] == 'decidix_health_indicators_v1',
      ) as Map<String, dynamic>;
      final coverage = healthDataset['geographic_coverage'] as String;
      expect(coverage, contains('Central Capital'));
      expect(coverage, contains('Frontier'));
      expect(coverage, contains('Steppe'));
    });

    // 6. Missing dataset and empty-state behavior
    test('6. Missing records parse as empty list without injecting fake entities', () {
      final emptyEnvelope = <String, dynamic>{
        'success': true,
        'data': <dynamic>[],
        'meta': <String, dynamic>{
          'total': 0,
          'page': 1,
          'limit': 10,
        },
      };

      final dataList = emptyEnvelope['data'] as List<dynamic>;
      final reports = dataList.map((item) => CitizenReport.fromJson(item as Map<String, dynamic>)).toList();

      expect(reports, isEmpty);
      expect(reports.length, 0);
    });
  });
}
